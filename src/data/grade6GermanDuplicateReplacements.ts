export function applyGrade6GermanDuplicateReplacements(topics: Topic[]): Topic[] {
  return topics.map(topic => {
    const ids = targetIds[topic.id];
    const replacements = tasks[topic.id];
    if (!ids || !replacements) return topic;
    if (ids.length !== replacements.length) throw new Error(`Grade 6 German replacement mismatch: ${topic.id}`);
    const map = new Map(ids.map((id, index) => [id, replacements[index]]));
    return {
      ...topic,
      exercises: topic.exercises.map((exercise): Exercise => {
        const replacement = map.get(exercise.id);
        if (!replacement) return exercise;
        if (exercise.type !== "fill-in-blank") throw new Error(`Grade 6 German type mismatch: ${exercise.id}`);
        return {
          ...exercise,
          question: replacement.question,
          questionEN: `German exercise: ${replacement.question}`,
          questionFR: `Exercice d’allemand : ${replacement.question}`,
          questionIT: `Esercizio di tedesco: ${replacement.question}`,
          answer: replacement.answer, answerEN: replacement.answer, answerFR: replacement.answer, answerIT: replacement.answer,
          hints: [replacement.hint, "Prüfe, ob deine Lösung grammatisch und inhaltlich genau passt."],
          hintsEN: ["Use the German-language clue in the exercise.", "Check that your German answer fits exactly."],
          hintsFR: ["Utilise l’indice en allemand dans l’exercice.", "Vérifie que ta réponse allemande convient exactement."],
          hintsIT: ["Usa l'indizio in tedesco nell'esercizio.", "Controlla che la risposta tedesca sia perfettamente adatta."],
        };
      }),
    };
  });
}
