export function applyGrade5GermanDuplicateReplacements(topics: Topic[]): Topic[] {
  return topics.map(topic => {
    const ids = targetIds[topic.id];
    const topicTasks = tasks[topic.id];
    if (!ids || !topicTasks) return topic;
    if (ids.length !== topicTasks.length) throw new Error(`Grade 5 German replacement mismatch: ${topic.id}`);
    const replacements = new Map(ids.map((id, index) => [id, topicTasks[index]]));
    return {
      ...topic,
      exercises: topic.exercises.map((exercise): Exercise => {
        const task = replacements.get(exercise.id);
        if (!task) return exercise;
        const [question, answer, hint] = task;
        return {
          ...exercise,
          question,
          questionEN: `German exercise: ${question}`,
          questionFR: `Exercice d’allemand : ${question}`,
          questionIT: `Esercizio di tedesco: ${question}`,
          answer,
          answerEN: answer,
          answerFR: answer,
          answerIT: answer,
          hints: [hint, "Prüfe, ob deine Lösung grammatisch und zum Satz genau passt."],
          hintsEN: ["Use the German-language clue in the sentence.", "Check that your German answer fits exactly."],
          hintsFR: ["Utilise l’indice en allemand dans la phrase.", "Vérifie que ta réponse allemande convient exactement."],
          hintsIT: ["Usa l'indizio in tedesco nella frase.", "Controlla che la risposta tedesca sia perfettamente adatta."],
          options: undefined,
          optionsEN: undefined,
          optionsFR: undefined,
          optionsIT: undefined,
        };
      }),
    };
  });
}
